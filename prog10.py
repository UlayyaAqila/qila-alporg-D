# perbandingan - jawaban ada 2 true false

# >,  <, >=,  <=, ==,  !=, is, isnot

x = 8

hasil = x > 9
print("x > 9 = ", hasil)

hasil = x < 9
print("x < 9 = ", hasil)

hasil = x >= 9
print("x >= 9 = ", hasil)

hasil = x <= 9
print("x <= 9 = ", hasil)

hasil = x == 9
print("x == 9 = ", hasil)

hasil = x != 9
print("x != 9 = ", hasil)

hasil = x is 9
print("x is 9 = ", hasil)

hasil = x is not 9
print("x is not 9 = ", hasil)






